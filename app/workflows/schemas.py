class CodegenTaskSchema(BaseModel):
    """
    Read-only representation of a Task record — returned inside
    CodegenRunDetail so callers can inspect per-task progress.
    """
    id:              str
    title:           str
    description:     Optional[str]      = None
    order_index:     int
    pattern_refs:    list[str]          = Field(default_factory=list)
    status:          str
