class TriggerRequirementsRequest(BaseModel):
    """Trigger the requirements-gathering workflow."""
    workflow_type:   WorkflowType       = WorkflowType.REQUIREMENTS
    input:           Optional[dict[str, Any]] = Field(default_factory=dict)
    document_ids:    Optional[list[str]]      = Field(
        default=None,
        description="Document IDs from the vector store to use as context",
    )
    idempotency_key: Optional[str] = None


class TriggerCodegenRequest(BaseModel):
    """
    Trigger Workflow 3 — Code Generation.

    The codegen workflow needs three pieces of context already stored on disk
    from earlier milestones:

    architecture_run_id
        The run_id of the completed architecture workflow whose approved task
        list we will execute.  The orchestrator loads the task list from the
        Run's output_data or from the artifacts directory.

    document_ids
        Optional extra document IDs to inject into the developer agent's
        context window (e.g. the original requirements doc).

    max_retries
        Per-task reviewer retry cap.  Defaults to 3 (configurable per call).
    """
    architecture_run_id: str = Field(
        ...,
        description="run_id of the approved architecture workflow to source the task list from",
    )
    document_ids:    Optional[list[str]] = Field(
        default=None,
        description="Additional document IDs to load into developer agent context",
    )
    max_retries:     int  = Field(
        default=3,
        ge=1,
        le=10,
        description="Maximum developer→reviewer retry loops per task",
    )
    idempotency_key: Optional[str] = None


class RunCreate(BaseModel):
    workflow_type: WorkflowType = WorkflowType.GENERIC
    input:         Optional[dict[str, Any]] = Field(default_factory=dict)


class ClarificationAnswer(BaseModel):
    """A single question-answer pair inside a clarification submission."""
    question_id: str
    answer:      str


class SubmitClarificationRequest(BaseModel):
    """
    REST fallback: submit answers to a pending clarification request.

    FIX: original schema had `answer: str` — router.py uses
    `body.request_id` and `body.answers` (list), so both are required here.
    """
    request_id: str
    answers:    list[ClarificationAnswer]


class ApproveRequest(BaseModel):
    comment: Optional[str] = None


class RejectRequest(BaseModel):
    """
    FIX: field renamed from `reason` → `feedback` to match router.py usage
    (`body.feedback` throughout _resume_with_approval).
    """
    feedback: Optional[str] = None


